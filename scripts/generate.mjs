// Generates lib/carbon_phoenix/web_components.ex from the
// custom-elements manifest shipped with @carbon/web-components.
//
//   npm install && npm run generate
//
import {readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync} from "node:fs"
import {fileURLToPath} from "node:url"
import {dirname, join} from "node:path"

const here = dirname(fileURLToPath(import.meta.url))
const manifestPath = join(here, "../node_modules/@carbon/web-components/custom-elements.json")
const outPath = join(here, "../lib/carbon_phoenix/web_components.ex")
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"))

const RESERVED = new Set(["rest", "inner_block", "on", "__changed__", "__given__"])
const str = s => JSON.stringify(s ?? "").replace(/#\{/g, "\\#{")
const sigil = s => (s ?? "").replace(/"""/g, "'''").split("\n").map(l => "  " + l.trimEnd()).join("\n")
const snake = s => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/-/g, "_").toLowerCase()

function elixirType(t) {
  const type = (t || "").toLowerCase()
  if (type === "boolean") return ":boolean"
  if (type === "string") return ":string"
  return ":any"
}

const out = []
const seen = new Set()
const tags = manifest.tags.filter(t => t.name.includes("-") && /^cds-/.test(t.name)).sort((a, b) => a.name.localeCompare(b.name))

for (const tag of tags) {
  const fn = snake(tag.name)
  if (seen.has(fn)) continue
  seen.add(fn)

  const attrs = []
  const names = new Set()
  for (const a of tag.attributes || []) {
    let key = snake(a.name)
    if (RESERVED.has(key) || names.has(key)) continue
    names.add(key)
    attrs.push({key, name: a.name, type: elixirType(a.type), desc: a.description, rawType: a.type, def: a.default})
  }

  const events = (tag.events || []).map(e => `  * \`${e.name}\` - ${(e.description || "").replace(/\n/g, " ")}`)
  const doc = [
    `Renders \`<${tag.name}>\`.`,
    "",
    tag.description || "",
    "",
    "Child elements are rendered inside the component. To target a named slot of the",
    "web component, pass `slot=\"name\"` on the child element.",
    ...(events.length
      ? ["", "## Events", "", ...events, "", "Use the `on` attribute (and an `id`) to forward them to the LiveView, e.g.",
         `\`on={%{"${tag.events[0].name}" => "my_event"}}\`.`]
      : [])
  ].join("\n")

  out.push(`  @doc ~S"""\n${sigil(doc)}\n  """`)
  out.push(`  attr :on, :map, default: %{}, doc: "map of DOM event name => LiveView event name; requires an \`id\`"`)
  out.push(`  attr :rest, :global, doc: "any additional HTML attributes"`)
  for (const a of attrs) {
    const docParts = [a.desc || "", a.rawType && !/^(boolean|string|number)$/i.test(a.rawType) ? `Type: \`${a.rawType}\`.` : "", a.def !== undefined ? `Carbon default: \`${a.def}\`.` : ""].filter(Boolean).join(" ").replace(/\s+/g, " ")
    out.push(`  attr :${a.key}, ${a.type}, default: nil, doc: ${str(docParts)}`)
  }
  out.push(`  slot :inner_block`)
  out.push(`  def ${fn}(assigns) do`)
  out.push(`    assigns = assign(assigns, :carbon_attrs, build(assigns, ${tag.name === "" ? "" : "@" + fn + "_attrs"}))`)
  out.push(`    ~H"""`)
  out.push(`    <${tag.name} {@carbon_attrs} {@rest}>{render_slot(@inner_block)}</${tag.name}>`)
  out.push(`    """`)
  out.push(`  end`)
  out.push(`  @${fn}_attrs ${"[" + attrs.map(a => `{:${a.key}, ${str(a.name)}}`).join(", ") + "]"}`)
  out.push("")
}

// attribute lists are module attributes; they must be defined before use
const body = out.join("\n")
const attrDefs = []
const fnBlocks = body.split(/\n(?=  @doc ~S)/)
const reordered = []
for (const block of fnBlocks) {
  const m = block.match(/\n  (@\w+_attrs \[.*\])\n?$/s)
  if (m) {
    reordered.push("  " + m[1] + "\n\n" + block.replace(m[0], "\n"))
  } else reordered.push(block)
}

const header = `# This file is GENERATED by scripts/generate.mjs
# from @carbon/web-components ${manifest.version || ""}. Do not edit by hand.
defmodule CarbonPhoenix.WebComponents do
  @moduledoc """
  One function component for every Carbon Design System web component
  (\`cds-*\`), generated from the package's custom elements manifest, so every
  attribute shown in the [Carbon web components storybook](https://web-components.carbondesignsystem.com/)
  is available as an assign.

  The function name is the tag name with underscores: \`<cds-button>\` is
  \`<.cds_button>\`, \`<cds-accordion-item>\` is \`<.cds_accordion_item>\`.

  ## Conventions

    * Attributes are snake_cased assigns (\`batch-action\` -> \`batch_action\`).
      Booleans render as present/absent, \`nil\` omits the attribute so Carbon's
      own default applies. Lists and maps are JSON encoded.
    * Anything else (\`class\`, \`id\`, \`phx-*\`, \`data-*\`, \`slot\`, ...) is passed
      through to the element.
    * Named slots are filled by giving the child element a \`slot="name"\`.
    * Carbon dispatches custom DOM events (e.g. \`cds-modal-closed\`). Forward them
      to the LiveView with \`on\` (requires an \`id\`):

          <.cds_modal id="m" open={@open} on={%{"cds-modal-closed" => "close_modal"}}>
            ...
          </.cds_modal>

      The LiveView receives \`handle_event("close_modal", %{"detail" => ..., "value" => ...}, socket)\`.
      This relies on the \`CarbonEvents\` hook from \`assets/js/carbon.js\`.

  For hand-tuned, Phoenix-style components (forms, tables, buttons, flash) see
  \`CarbonPhoenix.Components\`.
  """
  use Phoenix.Component

  @doc false
  def build(assigns, specs) do
    attrs =
      for {key, name} <- specs,
          value = Map.get(assigns, key),
          value != nil,
          into: %{},
          do: {name, encode(value)}

    case assigns[:on] do
      on when is_map(on) and map_size(on) > 0 ->
        Map.merge(attrs, %{"phx-hook" => "CarbonEvents", "data-carbon-on" => Jason.encode!(on)})

      _ ->
        attrs
    end
  end

  defp encode(value) when is_list(value) or (is_map(value) and not is_struct(value)),
    do: Jason.encode!(value)

  defp encode(value), do: value

`
writeFileSync(outPath, header + reordered.join("\n").replace(/\n{3,}/g, "\n\n") + "end\n")
console.log(`generated ${seen.size} components -> ${outPath}`)

